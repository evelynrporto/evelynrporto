#!/usr/bin/env node
// Generates the "Activity Pulse" contribution heatmap as a standalone SVG.
// readme-aura's built-in `github` object has no contribution calendar data,
// so this hits the GitHub GraphQL API directly (contributionsCollection).

const QUERY = `
query ($login: String!) {
  user(login: $login) {
    contributionsCollection {
      contributionCalendar {
        totalContributions
        weeks {
          contributionDays {
            contributionCount
            weekday
          }
        }
      }
    }
  }
}`;

async function fetchCalendar(login, token) {
  const res = await fetch('https://api.github.com/graphql', {
    method: 'POST',
    headers: {
      Authorization: `bearer ${token}`,
      'Content-Type': 'application/json',
      'User-Agent': 'readme-generator',
    },
    body: JSON.stringify({ query: QUERY, variables: { login } }),
  });
  if (!res.ok) throw new Error(`GitHub API ${res.status}: ${await res.text()}`);
  const json = await res.json();
  if (json.errors) throw new Error(json.errors.map((e) => e.message).join(', '));
  return json.data.user.contributionsCollection.contributionCalendar;
}

function mockCalendar() {
  const weeks = [];
  let total = 0;
  for (let w = 0; w < 53; w++) {
    const days = [];
    for (let d = 0; d < 7; d++) {
      const c = Math.random() < 0.35 ? 0 : Math.floor(Math.random() * 9);
      total += c;
      days.push({ contributionCount: c, weekday: d });
    }
    weeks.push({ contributionDays: days });
  }
  return { totalContributions: total, weeks };
}

function generateSVG(calendar) {
  const W = 860;
  const H = 180;
  const padX = 32;
  const gridTop = 56;
  const gridBottom = 22;
  const font = `'Inter', -apple-system, 'Segoe UI', sans-serif`;

  const weeks = calendar.weeks;
  const gridW = W - padX * 2;
  const step = gridW / weeks.length;
  const cellSize = Math.max(step - 3, 4);
  const gridH = H - gridTop - gridBottom;
  const rowStep = gridH / 7;
  const rowSize = Math.max(rowStep - 3, 4);

  const levelColor = (count) => {
    if (count === 0) return 'rgba(255,255,255,0.05)';
    if (count <= 2) return 'rgba(94,200,240,0.35)';
    if (count <= 5) return 'rgba(94,200,240,0.65)';
    if (count <= 9) return 'rgba(177,140,255,0.85)';
    return '#ffffff';
  };

  let cells = '';
  weeks.forEach((week, w) => {
    week.contributionDays.forEach((day) => {
      const x = padX + w * step;
      const cy = gridTop + day.weekday * rowStep;
      cells += `<rect x="${x.toFixed(1)}" y="${cy.toFixed(1)}" width="${cellSize.toFixed(1)}" height="${rowSize.toFixed(1)}" rx="2.5" fill="${levelColor(day.contributionCount)}" />`;
    });
  });

  return `<!-- Generated by scripts/generate-activity.js -->
<svg width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <radialGradient id="ap-g1" cx="50%" cy="50%" r="50%">
      <stop offset="0%" stop-color="rgba(90,20,190,0.35)" />
      <stop offset="70%" stop-color="rgba(90,20,190,0)" />
    </radialGradient>
  </defs>
  <rect x="0.75" y="0.75" width="${W - 1.5}" height="${H - 1.5}" rx="16" fill="#08080c" stroke="rgba(110,80,220,0.18)" stroke-width="1.5" />
  <ellipse cx="${W - 140}" cy="0" rx="260" ry="150" fill="url(#ap-g1)" />
  <text x="${padX}" y="30" font-family="${font}" font-size="11" font-weight="700" fill="rgba(155,140,210,0.6)" letter-spacing="3">ACTIVITY PULSE</text>
  <text x="${W - padX}" y="30" text-anchor="end" font-family="${font}" font-size="11" font-weight="700" fill="rgba(150,210,255,0.75)">${calendar.totalContributions} contributions</text>
  ${cells}
</svg>`;
}

(async () => {
  const login = process.env.GITHUB_USER || 'evelynrporto';
  const token = process.env.GITHUB_TOKEN;

  let calendar;
  if (token) {
    try {
      calendar = await fetchCalendar(login, token);
    } catch (e) {
      console.error(`generate-activity: ${e.message} — falling back to mock data`);
      calendar = mockCalendar();
    }
  } else {
    console.log('generate-activity: no GITHUB_TOKEN — using mock data for preview.');
    calendar = mockCalendar();
  }

  const svg = generateSVG(calendar);

  const fs = require('fs');
  const path = require('path');
  const outDir = path.resolve(process.cwd(), '.github/assets');
  fs.mkdirSync(outDir, { recursive: true });
  const outPath = path.join(outDir, 'activity-pulse.svg');
  fs.writeFileSync(outPath, svg, 'utf-8');
  console.log(`generate-activity: wrote ${outPath}`);
})();
